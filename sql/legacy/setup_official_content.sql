drop policy if exists "Admins can manage albums" on public.albums;
create policy "Admins can manage albums"
on public.albums
for all
to authenticated
using (
  exists (
    select 1
    from public.profiles
    where id = auth.uid()
      and role in ('admin', 'super_admin')
  )
)
with check (
  exists (
    select 1
    from public.profiles
    where id = auth.uid()
      and role in ('admin', 'super_admin')
  )
);


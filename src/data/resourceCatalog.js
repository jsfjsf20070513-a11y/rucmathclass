export const staticResourceCatalog = resourceCategories.flatMap((category, categoryIndex) =>
  category.items.map((item, index) => ({
    id: `catalog-${categoryIndex + 1}-${index + 1}`,
    category: category.label,
    title: item.title,
    url: item.url,
    tag: item.tag || '',
    description: item.desc,
    curator: '编者目录',
    sourceLabel: '固定目录',
    sourceKind: 'catalog',
  })),
)

function normalizeResourceValue(value = '') {
  return `${value}`.trim().toLowerCase()
}

function buildResourceIdentity(item) {
  return [
    normalizeResourceValue(item.url),
    normalizeResourceValue(item.title),
    normalizeResourceValue(item.category),
  ].join('::')
}

export function buildPublicResourceCatalog({ officialResources = [] }) {
  const official = officialResources.map((item) => ({
    ...item,
    sourceLabel: '正式发布',
    sourceKind: 'published',
  }))

  const seen = new Set()

  return [...official, ...staticResourceCatalog].filter((item) => {
    const identity = buildResourceIdentity(item)
    if (!identity || seen.has(identity)) {
      return false
    }

    seen.add(identity)
    return true
  })
}

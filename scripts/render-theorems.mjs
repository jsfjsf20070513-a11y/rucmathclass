import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import katex from 'katex'
import { dailyTheoremNotes } from '../src/data/siteContent.js'

const targetPath = resolve('src/data/dailyTheoremNotes.generated.js')

function renderDisplayHtml(expression, fallback) {
  try {
    return katex.renderToString(expression, {
      displayMode: true,
      output: 'html',
      throwOnError: false,
    })
  } catch {
    return fallback
  }
}

const renderedNotes = dailyTheoremNotes.map((note) => ({
  title: note.title,
  prelude: note.prelude,
  fallback: note.fallback,
  note: note.note,
  displayHtml: renderDisplayHtml(note.displayExpression, note.fallback),
}))

const fileContents = `${[
  '// This file is generated by scripts/render-theorems.mjs.',
  '// Edit src/data/siteContent.js and rerun the generator instead.',
  '',
  `export const dailyTheoremNotes = ${JSON.stringify(renderedNotes, null, 2)}`,
  '',
].join('\n')}`

await mkdir(dirname(targetPath), { recursive: true })
await writeFile(targetPath, fileContents)
